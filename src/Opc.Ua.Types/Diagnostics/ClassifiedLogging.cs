using System;
using System.Collections;
using System.Collections.Generic;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Logging.Abstractions;

namespace Opc.Ua
{
    /// <summary>
    /// Keeps classified log values visible in logging pipelines that do not
    /// redact.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Log messages whose parameters carry a data classification (see
    /// <see cref="OpcUaDataClasses"/>) are generated by the extended logging
    /// source generator of <c>Microsoft.Extensions.Telemetry.Abstractions</c>.
    /// The generated code only formats a classified value after the
    /// redacting logger of <c>Microsoft.Extensions.Telemetry</c> has
    /// processed it. Any other logger prints <c>(null)</c> in its place and
    /// does not see the value in the structured state.
    /// </para>
    /// <para>
    /// The loggers returned by <see cref="WithClassifiedPassThrough(ILogger)"/>
    /// close that gap: when the inner logger does not redact, they hand the
    /// raw classified values to it, so the log text and structured state are
    /// the same as without classification. When the inner logger is the
    /// redacting logger, it is returned unchanged and redaction applies.
    /// </para>
    /// <para>
    /// Components that log classified values create their logger with
    /// <see cref="CreateClassifiedLogger{T}(ITelemetryContext)"/> or wrap a
    /// logger they receive with <see cref="WithClassifiedPassThrough"/>.
    /// Other loggers are left untouched.
    /// </para>
    /// </remarks>
    public static class ClassifiedLogging
    {
        /// <summary>
        /// Wrap a logger so that classified values are passed through to it
        /// unless it redacts them.
        /// </summary>
        /// <param name="logger">The logger to wrap.</param>
        /// <returns>The wrapped logger, or <paramref name="logger"/>
        /// itself if no wrapping is needed.</returns>
        /// <exception cref="ArgumentNullException">
        /// <paramref name="logger"/> is <c>null</c>.</exception>
        public static ILogger WithClassifiedPassThrough(this ILogger logger)
        {
            if (logger == null)
            {
                throw new ArgumentNullException(nameof(logger));
            }
            if (!NeedsPassThrough(logger))
            {
                return logger;
            }
            return new PassThroughLogger(logger, MayWrapRedactingLogger(logger));
        }

        /// <summary>
        /// Create a typed logger from the factory with classified values
        /// passed through unless the factory's loggers redact them. The
        /// category name is the same as for
        /// <see cref="LoggerFactoryExtensions.CreateLogger{T}(ILoggerFactory)"/>.
        /// </summary>
        /// <typeparam name="T">The category type.</typeparam>
        /// <param name="factory">The logger factory.</param>
        /// <exception cref="ArgumentNullException">
        /// <paramref name="factory"/> is <c>null</c>.</exception>
        public static ILogger<T> CreateClassifiedLogger<T>(this ILoggerFactory factory)
        {
            if (factory == null)
            {
                throw new ArgumentNullException(nameof(factory));
            }
            // The non generic overload returns the factory's own logger (with
            // the same category name as Logger<T>), which is what is inspected.
#pragma warning disable CA2263 // Prefer generic overload when type is known
            ILogger inner = factory.CreateLogger(typeof(T));
#pragma warning restore CA2263 // Prefer generic overload when type is known
            if (!NeedsPassThrough(inner))
            {
                return factory.CreateLogger<T>();
            }
            return new PassThroughLogger<T>(inner, MayWrapRedactingLogger(inner));
        }

        /// <summary>
        /// Create a typed logger from the telemetry context with classified
        /// values passed through unless the loggers redact them. The category
        /// name is the same as for
        /// <see cref="TelemetryExtensions.CreateLogger{TContext}(ITelemetryContext)"/>.
        /// </summary>
        /// <typeparam name="T">The category type.</typeparam>
        /// <param name="telemetry">The telemetry context to use.</param>
        public static ILogger<T> CreateClassifiedLogger<T>(this ITelemetryContext? telemetry)
        {
            return telemetry.GetLoggerFactory().CreateClassifiedLogger<T>();
        }

        /// <summary>
        /// Create a logger from the telemetry context with classified values
        /// passed through unless the loggers redact them. The category name is
        /// the same as for
        /// <see cref="TelemetryExtensions.CreateLogger{TContext}(ITelemetryContext, TContext)"/>.
        /// </summary>
        /// <typeparam name="TContext">The type of the context.</typeparam>
        /// <param name="telemetry">The telemetry context to use.</param>
        /// <param name="context">A context to infer the category name from.</param>
        public static ILogger CreateClassifiedLogger<TContext>(
            this ITelemetryContext? telemetry,
            TContext context)
        {
            return telemetry.CreateLogger(context).WithClassifiedPassThrough();
        }

        /// <summary>
        /// Create a logger from the telemetry context with classified values
        /// passed through unless the loggers redact them.
        /// </summary>
        /// <param name="telemetry">The telemetry context to use.</param>
        /// <param name="categoryName">The category name.</param>
        public static ILogger CreateClassifiedLogger(
            this ITelemetryContext? telemetry,
            string categoryName)
        {
            return telemetry.CreateLogger(categoryName).WithClassifiedPassThrough();
        }

        /// <summary>
        /// Create a logger from the factory with classified values passed
        /// through unless the factory's loggers redact them.
        /// </summary>
        /// <param name="factory">The logger factory.</param>
        /// <param name="categoryName">The category name.</param>
        /// <exception cref="ArgumentNullException">
        /// <paramref name="factory"/> is <c>null</c>.</exception>
        public static ILogger CreateClassifiedLogger(
            this ILoggerFactory factory,
            string categoryName)
        {
            if (factory == null)
            {
                throw new ArgumentNullException(nameof(factory));
            }
            return factory.CreateLogger(categoryName).WithClassifiedPassThrough();
        }

        /// <summary>
        /// Whether the logger needs the pass-through. Loggers that already
        /// handle classified values (the redacting logger of
        /// Microsoft.Extensions.Telemetry, which is internal and therefore
        /// identified by name, and the loggers of this class) and loggers
        /// that never log do not.
        /// </summary>
        private static bool NeedsPassThrough(ILogger logger)
        {
            return logger is not (IClassifiedDataAwareLogger or LoggerUtils.Null or NullLogger) &&
                !string.Equals(
                    logger.GetType().FullName,
                    kExtendedLoggerTypeName,
                    StringComparison.Ordinal);
        }

        /// <summary>
        /// Whether the logger is a known wrapper that can hide the redacting
        /// logger of Microsoft.Extensions.Telemetry, such as the
        /// <see cref="Logger{T}"/> that dependency injection hands out for
        /// <see cref="ILogger{TCategoryName}"/>. Such a logger must receive
        /// the original message state, or redaction is bypassed.
        /// </summary>
        private static bool MayWrapRedactingLogger(ILogger logger)
        {
            Type type = logger.GetType();
            return type.IsGenericType && type.GetGenericTypeDefinition() == typeof(Logger<>);
        }

        /// <summary>
        /// Fill the slots the generated formatter reads classified values
        /// from with the raw values. A redacting logger that runs on the same
        /// state afterwards overwrites them again.
        /// </summary>
        internal static void FillRedactedTags(LoggerMessageState state)
        {
            LoggerMessageState.ClassifiedTag[] classified = state.ClassifiedTagArray;
            KeyValuePair<string, object?>[] redacted = state.RedactedTagArray;
            for (int ii = 0; ii < state.ClassifiedTagsCount; ii++)
            {
                redacted[ii] = new(classified[ii].Name, classified[ii].Value);
            }
        }

        /// <summary>
        /// Forward a log entry to a logger that does not redact. Classified
        /// values are filled in for the formatter. Unless the original state
        /// must be kept, they are also included in the structured state
        /// handed to the logger.
        /// </summary>
        /// <typeparam name="TState">The type of the state.</typeparam>
        internal static void LogPassThrough<TState>(
            ILogger inner,
            bool keepState,
            LogLevel logLevel,
            EventId eventId,
            TState state,
            Exception? exception,
            Func<TState, Exception?, string> formatter)
        {
            if (typeof(TState) == typeof(LoggerMessageState) &&
                state is LoggerMessageState messageState &&
                messageState.ClassifiedTagsCount > 0)
            {
                if (!inner.IsEnabled(logLevel))
                {
                    return;
                }
                FillRedactedTags(messageState);
                if (keepState)
                {
                    // The text is unchanged and a redacting logger further
                    // down still redacts, but a logger that does not redact
                    // misses the classified values in the structured state.
                    inner.Log(logLevel, eventId, state, exception, formatter);
                    return;
                }
                inner.Log(
                    logLevel,
                    eventId,
                    new PassThroughState(
                        messageState,
                        (Func<LoggerMessageState, Exception?, string>)(object)formatter),
                    exception,
                    static (s, e) => s.Format(e));
                return;
            }
            inner.Log(logLevel, eventId, state, exception, formatter);
        }

        private const string kExtendedLoggerTypeName = "Microsoft.Extensions.Logging.ExtendedLogger";

        /// <summary>
        /// Marks loggers that handle classified values themselves.
        /// </summary>
        internal interface IClassifiedDataAwareLogger;

        /// <summary>
        /// The structured state handed to a logger that does not redact: the
        /// tags of the message state followed by the classified tags with
        /// their raw values, with the original format last as in the
        /// standard logging source generator.
        /// </summary>
        private sealed class PassThroughState : IReadOnlyList<KeyValuePair<string, object?>>
        {
            public PassThroughState(
                LoggerMessageState state,
                Func<LoggerMessageState, Exception?, string> formatter)
            {
                m_state = state;
                m_formatter = formatter;
                int count = state.TagsCount;
                m_originalFormatIndex = -1;
                for (int ii = 0; ii < count; ii++)
                {
                    if (string.Equals(
                        state.TagArray[ii].Key,
                        kOriginalFormat,
                        StringComparison.Ordinal))
                    {
                        m_originalFormatIndex = ii;
                        break;
                    }
                }
            }

            public int Count => m_state.TagsCount + m_state.ClassifiedTagsCount;

            public KeyValuePair<string, object?> this[int index]
            {
                get
                {
                    if ((uint)index >= (uint)Count)
                    {
                        throw new ArgumentOutOfRangeException(nameof(index));
                    }
                    int tags = m_state.TagsCount;
                    if (m_originalFormatIndex < 0)
                    {
                        return index < tags
                            ? m_state.TagArray[index]
                            : Classified(index - tags);
                    }
                    // Tags without the original format, then the classified
                    // tags, then the original format.
                    if (index == Count - 1)
                    {
                        return m_state.TagArray[m_originalFormatIndex];
                    }
                    if (index < tags - 1)
                    {
                        return m_state.TagArray[
                            index < m_originalFormatIndex ? index : index + 1];
                    }
                    return Classified(index - (tags - 1));
                }
            }

            public string Format(Exception? exception)
            {
                return m_formatter(m_state, exception);
            }

            public IEnumerator<KeyValuePair<string, object?>> GetEnumerator()
            {
                for (int ii = 0; ii < Count; ii++)
                {
                    yield return this[ii];
                }
            }

            IEnumerator IEnumerable.GetEnumerator()
            {
                return GetEnumerator();
            }

            public override string ToString()
            {
                return Format(null);
            }

            private KeyValuePair<string, object?> Classified(int index)
            {
                LoggerMessageState.ClassifiedTag tag = m_state.ClassifiedTagArray[index];
                return new(tag.Name, tag.Value);
            }

            private const string kOriginalFormat = "{OriginalFormat}";
            private readonly LoggerMessageState m_state;
            private readonly Func<LoggerMessageState, Exception?, string> m_formatter;
            private readonly int m_originalFormatIndex;
        }

        /// <summary>
        /// Logger that passes classified values through to a logger that
        /// does not redact.
        /// </summary>
        private class PassThroughLogger : ILogger, IClassifiedDataAwareLogger
        {
            public PassThroughLogger(ILogger inner, bool keepState)
            {
                m_inner = inner;
                m_keepState = keepState;
            }

            /// <inheritdoc/>
            public IDisposable? BeginScope<TState>(TState state) where TState : notnull
            {
                return m_inner.BeginScope(state);
            }

            /// <inheritdoc/>
            public bool IsEnabled(LogLevel logLevel)
            {
                return m_inner.IsEnabled(logLevel);
            }

            /// <inheritdoc/>
            public void Log<TState>(
                LogLevel logLevel,
                EventId eventId,
                TState state,
                Exception? exception,
                Func<TState, Exception?, string> formatter)
            {
                LogPassThrough(m_inner, m_keepState, logLevel, eventId, state, exception, formatter);
            }

            /// <inheritdoc/>
            public override string? ToString()
            {
                return m_inner.ToString();
            }

            private readonly ILogger m_inner;
            private readonly bool m_keepState;
        }

        /// <summary>
        /// Typed variant of <see cref="PassThroughLogger"/>.
        /// </summary>
        /// <typeparam name="T">The category type.</typeparam>
        private sealed class PassThroughLogger<T> : PassThroughLogger, ILogger<T>
        {
            public PassThroughLogger(ILogger inner, bool keepState)
                : base(inner, keepState)
            {
            }
        }
    }
}
